/** aria-label for closing the lightbox. */
export function describeLightboxCloseAriaLabel(): string {
  return "Close"
}

/** aria-label for sharing the current photo. */
export function describeLightboxShareAriaLabel(): string {
  return "Share"
}

/** aria-label for previous photo/shot. */
export function describeLightboxPreviousAriaLabel(): string {
  return "Previous"
}

/** aria-label for next photo/shot. */
export function describeLightboxNextAriaLabel(): string {
  return "Next"
}
