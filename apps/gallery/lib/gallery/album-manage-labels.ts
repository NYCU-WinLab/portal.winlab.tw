/** aria-label for selecting every photo in the album editor. */
export function describeSelectAllPhotosAriaLabel(): string {
  return "Select all photos"
}

/** aria-label for moving a photo earlier in the album. */
export function describeMoveUpAriaLabel(): string {
  return "Move up"
}

/** aria-label for moving a photo later in the album. */
export function describeMoveDownAriaLabel(): string {
  return "Move down"
}

/** aria-label for removing a photo from the album. */
export function describeRemoveFromAlbumAriaLabel(): string {
  return "Remove from album"
}
